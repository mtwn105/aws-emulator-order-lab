"""Provision a fresh, local-only lab. One prefix per run; no cloud deployment."""
import io
import json
from pathlib import Path
import zipfile

from local_aws import assert_local, client, connection, names
from workflow import definition


def package():
    target = io.BytesIO()
    with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED) as archive:
        for name in ("handler.py", "local_aws.py"):
            archive.write(Path(__file__).parent / name, name)
        # Python SDK modules are supplied by the emulator's function runtime.
        # Vendoring CPython boto3 shadows that adapter and fails in this runtime.
    return target.getvalue()


def queue(name, attributes=None):
    sqs = client("sqs")
    url = sqs.create_queue(QueueName=name, Attributes=attributes or {})["QueueUrl"]
    arn = sqs.get_queue_attributes(QueueUrl=url, AttributeNames=["QueueArn"])["Attributes"]["QueueArn"]
    return {"url": url, "arn": arn}


def allow_source(target, service, source_arn):
    policy = {"Version": "2012-10-17", "Statement": [{"Effect": "Allow",
        "Principal": {"Service": service}, "Action": "sqs:SendMessage", "Resource": target["arn"],
        "Condition": {"ArnEquals": {"aws:SourceArn": source_arn},
                      "StringEquals": {"aws:SourceAccount": "000000000000"}}}]}
    client("sqs").set_queue_attributes(QueueUrl=target["url"], Attributes={"Policy": json.dumps(policy)})


def runtime_policy(n):
    # Baseline generated by IAM Policy Autopilot; scope resources to this lab.
    policy = json.loads((Path(__file__).parent / "runtime-policy.json").read_text())
    resources = {
        "dynamodb": [f"arn:aws:dynamodb:us-east-1:000000000000:table/{n['table']}"],
        "events": [f"arn:aws:events:us-east-1:000000000000:event-bus/{n['bus']}"],
        "logs": [f"arn:aws:logs:us-east-1:000000000000:log-group:{n['logs']}:log-stream:orders"],
        "s3": [f"arn:aws:s3:::{n['bucket']}/*"], "sns": [n["topic"]],
        "ssm": [f"arn:aws:ssm:us-east-1:000000000000:parameter{n['parameter']}"],
        "states": [n["machine"], n["machine"].replace(":stateMachine:", ":execution:") + ":*"],
    }
    for statement in policy["Statement"]:
        statement["Resource"] = resources[statement["Action"][0].split(":")[0]]
    return policy


def main():
    assert_local()
    n = names()
    db = client("dynamodb")
    db.create_table(TableName=n["table"], AttributeDefinitions=[{"AttributeName": "orderId", "AttributeType": "S"}],
                    KeySchema=[{"AttributeName": "orderId", "KeyType": "HASH"}], BillingMode="PAY_PER_REQUEST")
    db.get_waiter("table_exists").wait(TableName=n["table"], WaiterConfig={"Delay": 1, "MaxAttempts": 30})
    client("s3").create_bucket(Bucket=n["bucket"])
    client("ssm").put_parameter(Name=n["parameter"], Type="String", Value="5")
    client("logs").create_log_group(logGroupName=n["logs"])
    client("logs").create_log_stream(logGroupName=n["logs"], logStreamName="orders")
    dlq = queue(n["prefix"] + "-dlq")
    pending = queue(n["prefix"] + "-events", {"VisibilityTimeout": "180",
                    "RedrivePolicy": json.dumps({"deadLetterTargetArn": dlq["arn"], "maxReceiveCount": "3"})})
    inboxes = [queue(n["prefix"] + "-" + suffix) for suffix in ("customer", "audit")]
    topic = client("sns").create_topic(Name=n["prefix"] + "-completed")["TopicArn"]
    for inbox in inboxes:
        allow_source(inbox, "sns.amazonaws.com", topic)
        client("sns").subscribe(TopicArn=topic, Protocol="sqs", Endpoint=inbox["arn"],
                                Attributes={"RawMessageDelivery": "true"})
    events = client("events")
    events.create_event_bus(Name=n["bus"])
    rule = events.put_rule(Name="completed", EventBusName=n["bus"],
        EventPattern=json.dumps({"source": ["orderlab.orders"], "detail-type": ["OrderCompleted"]}))["RuleArn"]
    allow_source(pending, "events.amazonaws.com", rule)
    response = events.put_targets(Rule="completed", EventBusName=n["bus"], Targets=[{"Id": "notifications", "Arn": pending["arn"]}])
    if response.get("FailedEntryCount", 0):
        raise RuntimeError("EventBridge target registration failed")

    # Service integrations validate some role prerequisites even in the emulator.
    # This is still not evidence of production IAM enforcement.
    iam = client("iam")
    iam.create_role(RoleName=n["prefix"] + "-local", AssumeRolePolicyDocument=json.dumps({
        "Version": "2012-10-17", "Statement": [{"Effect": "Allow", "Action": "sts:AssumeRole",
        "Principal": {"Service": "lambda.amazonaws.com"}}]}))
    function_arn = f"arn:aws:lambda:us-east-1:000000000000:function:{n['function']}"
    iam.put_role_policy(RoleName=n["prefix"] + "-local", PolicyName="queue-polling",
        PolicyDocument=json.dumps({"Version": "2012-10-17", "Statement": [{"Effect": "Allow",
            "Action": ["sqs:ReceiveMessage", "sqs:DeleteMessage", "sqs:GetQueueAttributes"],
            "Resource": pending["arn"]}]}))
    iam.put_role_policy(RoleName=n["prefix"] + "-local", PolicyName="runtime",
                        PolicyDocument=json.dumps(runtime_policy(n)))
    iam.create_role(RoleName=n["prefix"] + "-workflow", AssumeRolePolicyDocument=json.dumps({
        "Version": "2012-10-17", "Statement": [{"Effect": "Allow", "Action": "sts:AssumeRole",
        "Principal": {"Service": "states.amazonaws.com"}, "Condition": {
            "StringEquals": {"aws:SourceAccount": "000000000000"},
            "ArnEquals": {"aws:SourceArn": n["machine"]}}}]}))
    iam.put_role_policy(RoleName=n["prefix"] + "-workflow", PolicyName="invoke-handler",
        PolicyDocument=json.dumps({"Version": "2012-10-17", "Statement": [{"Effect": "Allow",
            "Action": "lambda:InvokeFunction", "Resource": function_arn}]}))
    endpoint, _, _, ca = connection()
    variables = {"LAB_ENDPOINT": endpoint, "LAB_EMULATOR_DIR": str(Path(ca).parent.resolve()),
                 "LAB_PREFIX": n["prefix"], "LAB_FUNCTION_RUNTIME": "1"}
    lamb = client("lambda")
    lamb.create_function(FunctionName=n["function"], Runtime="python3.12", Role=n["role"], Handler="handler.handler",
                         Code={"ZipFile": package()}, Timeout=20, MemorySize=256, Environment={"Variables": variables})
    lamb.get_waiter("function_active_v2").wait(FunctionName=n["function"], WaiterConfig={"Delay": 1, "MaxAttempts": 30})
    machine = client("stepfunctions").create_state_machine(name=n["prefix"],
        definition=json.dumps(definition(function_arn)), roleArn=n["state_role"], type="STANDARD")["stateMachineArn"]
    mapping = lamb.create_event_source_mapping(EventSourceArn=pending["arn"], FunctionName=n["function"],
        BatchSize=1, Enabled=True, FunctionResponseTypes=["ReportBatchItemFailures"])
    gateway = client("apigateway")
    api = gateway.create_rest_api(name=n["prefix"])["id"]
    root = gateway.get_resources(restApiId=api)["items"][0]["id"]
    resource = gateway.create_resource(restApiId=api, parentId=root, pathPart="orders")["id"]
    gateway.put_method(restApiId=api, resourceId=resource, httpMethod="POST", authorizationType="AWS_IAM")
    gateway.put_integration(restApiId=api, resourceId=resource, httpMethod="POST", type="AWS_PROXY",
        integrationHttpMethod="POST", uri=f"arn:aws:apigateway:us-east-1:lambda:path/2015-03-31/functions/{function_arn}/invocations")
    lamb.add_permission(FunctionName=n["function"], StatementId="gateway", Action="lambda:InvokeFunction",
        Principal="apigateway.amazonaws.com", SourceArn=f"arn:aws:execute-api:us-east-1:000000000000:{api}/*/POST/orders")
    output = {"api": api, "resource": resource, "machine": machine, "queue": pending, "inboxes": inboxes,
              "dlq": dlq, "mapping": mapping["UUID"], "names": n}
    Path(".local").mkdir(exist_ok=True)
    Path(".local/resources.json").write_text(json.dumps(output, indent=2) + "\n")
    print("Created local lab. Run: python integration.py")


if __name__ == "__main__":
    main()
